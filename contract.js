  function escH(s) { return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;"); }
  function runsH(runs) { return runs.map(function (r) { var t = escH(r.text).replace(/\n/g, "<br>"); return r.b ? "<b>" + t + "</b>" : t; }).join(""); }
  function toHTML(doc) {
    return doc.blocks.map(function (b) {
      switch (b.t) {
        case "title": return '<div class="c-title">' + escH(b.text) + "</div>";
        case "subtitle": return '<div class="c-sub">' + escH(b.text) + "</div>";
        case "citydate": return '<div class="c-cd"><span>' + escH(b.left) + "</span><span>" + escH(b.right) + "</span></div>";
        case "right": return '<div class="c-right">' + escH(b.text).replace(/\n/g, "<br>") + "</div>";
        case "h": return '<div class="c-h">' + escH(b.text) + "</div>";
        case "p": return '<p class="c-p' + (b.ind ? " ind" : "") + '">' + runsH(b.runs) + "</p>";
        case "li": return '<p class="c-li">– ' + runsH(b.runs) + "</p>";
        case "table": return '<table class="c-tbl">' + b.rows.map(function (r) { return "<tr>" + r.map(function (c) { return "<td>" + runsH(c) + "</td>"; }).join("") + "</tr>"; }).join("") + "</table>";
        case "sig": return '<div class="c-sig"><div>' + b.left.map(function (l) { return "<div>" + runsH(l) + "</div>"; }).join("") + "</div><div>" + b.right.map(function (l) { return "<div>" + runsH(l) + "</div>"; }).join("") + "</div></div>";
        case "pb": return '<hr class="c-pb">';
      }
      return "";
    }).join("\n");
  }

