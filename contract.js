  function tblX(widths, rows, on, cellPara) {
    var total = widths.reduce(function (a, b) { return a + b; }, 0);
    var x = '<w:tbl><w:tblPr><w:tblW w:w="' + total + '" w:type="dxa"/>' + borders(on) + '<w:tblLayout w:type="fixed"/><w:tblCellMar><w:top w:w="20" w:type="dxa"/><w:left w:w="80" w:type="dxa"/><w:bottom w:w="20" w:type="dxa"/><w:right w:w="80" w:type="dxa"/></w:tblCellMar></w:tblPr><w:tblGrid>';
    widths.forEach(function (w) { x += '<w:gridCol w:w="' + w + '"/>'; });
    x += "</w:tblGrid>";
    rows.forEach(function (row) {
      x += "<w:tr><w:trPr><w:cantSplit/></w:trPr>";
      row.forEach(function (cell, i) {
        x += '<w:tc><w:tcPr><w:tcW w:w="' + widths[i] + '" w:type="dxa"/></w:tcPr>';
        x += cellPara(cell);
        x += "</w:tc>";
      });
      x += "</w:tr>";
    });
    return x + "</w:tbl>";
  }
