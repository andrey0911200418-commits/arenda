  function escX(s) { return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;"); }
  function rX(r, o) {
    o = o || {};
    var rpr = "";
    if (r.b || o.b) rpr += "<w:b/><w:bCs/>";
    var sz = r.sz || o.sz; if (sz) rpr += '<w:sz w:val="' + sz + '"/><w:szCs w:val="' + sz + '"/>';
    var parts = String(r.text).split("\n"), out = "";
    parts.forEach(function (p, i) { if (i) out += "<w:br/>"; out += '<w:t xml:space="preserve">' + escX(p) + "</w:t>"; });
    return "<w:r>" + (rpr ? "<w:rPr>" + rpr + "</w:rPr>" : "") + out + "</w:r>";
  }
  function pX(runs, o) {
    o = o || {};
    var ppr = "";
    if (o.keepNext) ppr += "<w:keepNext/>";
    ppr += '<w:spacing w:before="' + (o.before || 0) + '" w:after="' + (o.after === undefined ? 40 : o.after) + '" w:line="240" w:lineRule="auto"/>';
    if (o.indFirst || o.indLeft || o.hanging) ppr += "<w:ind" + (o.indLeft ? ' w:left="' + o.indLeft + '"' : "") + (o.hanging ? ' w:hanging="' + o.hanging + '"' : "") + (o.indFirst ? ' w:firstLine="' + o.indFirst + '"' : "") + "/>";
    ppr += '<w:jc w:val="' + (o.jc || "both") + '"/>';
    return "<w:p><w:pPr>" + ppr + "</w:pPr>" + runs.map(function (r) { return rX(r, o); }).join("") + "</w:p>";
  }
